-- Compact territory history. The legacy tables stay untouched as the conversion source and
-- the rollback path; `sequoia-server history-convert` fills these tables from them.

CREATE TABLE history_territory (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

-- One row per exact display identity, so a rename or recolour never rewrites old facts.
CREATE TABLE history_guild (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid TEXT NOT NULL,
    name TEXT NOT NULL,
    prefix TEXT NOT NULL,
    color INTEGER CHECK (color BETWEEN 0 AND 16777215),
    UNIQUE NULLS NOT DISTINCT (uuid, name, prefix, color)
);

-- Ownership facts in stream order. A canonical batch shares one stream position; `ordinal`
-- orders its changes. `source`: 0 legacy event, 1 poller, 2 canonical ingest. `take` marks a
-- change of owning guild, as opposed to a first sighting or an acquisition/metadata change.
CREATE TABLE history_fact (
    stream_seq BIGINT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    acquired_at TIMESTAMPTZ NOT NULL,
    guild_id INTEGER NOT NULL,
    prev_guild_id INTEGER,
    ordinal SMALLINT NOT NULL,
    territory_id SMALLINT NOT NULL,
    source SMALLINT NOT NULL,
    take BOOLEAN NOT NULL,
    PRIMARY KEY (stream_seq, ordinal)
);

CREATE INDEX history_fact_recorded ON history_fact (recorded_at);

-- Complete ownership at `taken_at`: replay continues with facts recorded after it. `source`:
-- 0 converted legacy snapshot, 1 derived from a legacy snapshot and the legacy events after
-- it, 2 written by the history writer in the transaction of the fact at `through_seq`.
CREATE TABLE history_checkpoint (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    taken_at TIMESTAMPTZ NOT NULL,
    through_seq BIGINT NOT NULL,
    source SMALLINT NOT NULL,
    legacy_snapshot_id BIGINT UNIQUE,
    ownership BYTEA NOT NULL
);

CREATE INDEX history_checkpoint_taken ON history_checkpoint (taken_at);

-- Owner changes per UTC day and territory, maintained with the facts.
CREATE TABLE history_heat_day (
    day DATE NOT NULL,
    territory_id SMALLINT NOT NULL,
    takes INTEGER NOT NULL,
    PRIMARY KEY (day, territory_id)
);

CREATE TABLE history_meta (
    id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id),
    earliest_at TIMESTAMPTZ,
    latest_at TIMESTAMPTZ,
    earliest_take_at TIMESTAMPTZ,
    fact_count BIGINT NOT NULL DEFAULT 0,
    latest_fact_seq BIGINT,
    -- Stream positions up to here may have been published; a restart continues above it.
    seq_reserved_through BIGINT NOT NULL DEFAULT 0,
    -- Conversion watermarks over the legacy sources.
    legacy_events_through BIGINT NOT NULL DEFAULT 0,
    legacy_snapshots_through BIGINT NOT NULL DEFAULT 0,
    legacy_archive_through BIGINT NOT NULL DEFAULT 0
);

INSERT INTO history_meta (id) VALUES (TRUE);

-- Compact canonical archive: repeated static fields are stored once per version and the
-- runtime payload in a verified typed encoding (raw JSON only when that would lose data).
CREATE TABLE canonical_static (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    digest BYTEA NOT NULL UNIQUE,
    fields JSONB NOT NULL
);

CREATE TABLE canonical_source (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE canonical_report (
    id BIGINT PRIMARY KEY DEFAULT nextval('canonical_territory_updates_id_seq'),
    received_at TIMESTAMPTZ NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    acquired_at TIMESTAMPTZ,
    confidence DOUBLE PRECISION NOT NULL,
    guild_id INTEGER,
    static_id INTEGER,
    reporter_count INTEGER NOT NULL,
    territory_id SMALLINT NOT NULL,
    source_id SMALLINT NOT NULL,
    visibility SMALLINT NOT NULL,
    idempotency_key TEXT,
    runtime BYTEA,
    raw_payload JSONB
);

CREATE UNIQUE INDEX canonical_report_idempotency
    ON canonical_report (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX canonical_report_observed ON canonical_report USING brin (observed_at);

-- Production suppresses deletes on the legacy history tables; keep that policy for the
-- tables that replace them.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'territory_events'::regclass AND NOT tgisinternal
          AND tgfoid = 'prevent_history_table_delete'::regproc
    ) THEN
        CREATE TRIGGER prevent_delete_history_fact BEFORE DELETE ON history_fact
            FOR EACH ROW EXECUTE FUNCTION prevent_history_table_delete();
        CREATE TRIGGER prevent_delete_history_checkpoint BEFORE DELETE ON history_checkpoint
            FOR EACH ROW EXECUTE FUNCTION prevent_history_table_delete();
    END IF;
EXCEPTION WHEN undefined_function THEN
    NULL;
END $$;
